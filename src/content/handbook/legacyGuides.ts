import {
  exercise,
  type FeynmanGuide,
  type ExerciseDraft,
  type ChapterId,
  type HandbookLevel,
} from './model'

function guide(
  lessonId: string,
  chapterId: ChapterId,
  level: HandbookLevel,
  plain: string,
  why: string,
  prompt: string,
  selfCheck: string[],
  relatedIds: string[],
  prediction: ExerciseDraft,
  aliases: string[] = [],
): FeynmanGuide {
  return {
    lessonId,
    chapterId,
    level,
    plain,
    why,
    prompt,
    selfCheck,
    relatedIds,
    aliases,
    prediction: exercise(`${lessonId}-hb-predict`, prediction),
  }
}
