import { readFile, writeFile, mkdir, rename, stat, rm } from 'node:fs/promises'
import { resolve } from 'node:path'
import { createHash } from 'node:crypto'
import { format, type Options } from 'prettier'
import type { ContentPackage } from '../src/content/ingestion'
export const packageDigest = (pkg: ContentPackage) =>
  createHash('sha256').update(JSON.stringify(pkg)).digest('hex')
/** Immutable staging + a single activation rename. Failed staging never edits the active registry. */
export async function activateContentBatch(
  folder: string,
  registry: string,
  current: ContentPackage[],
  accepted: ContentPackage[],
  config: Options = {},
  beforeActivate?: () => Promise<void>,
) {
  const known = new Map(current.map((p) => [p.id, p]))
  if (
    new Set(accepted.map((p) => p.id)).size !== accepted.length ||
    [...current, ...accepted].some((p) => !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(p.id))
  )
    throw new Error('Unsafe or duplicate package activation ID.')
  await mkdir(folder, { recursive: true })
  for (const pkg of accepted) {
    const digest = packageDigest(pkg),
      path = resolve(folder, pkg.id + '--' + digest.slice(0, 16) + '.json')
    try {
      const previous = JSON.parse(await readFile(path, 'utf8')) as ContentPackage
      if (packageDigest(previous) !== digest) throw new Error('Staged content digest mismatch.')
    } catch (error) {
      if (!error || typeof error !== 'object' || !('code' in error) || error.code !== 'ENOENT')
        throw error
      await writeFile(path, await format(JSON.stringify(pkg), { ...config, parser: 'json' }), {
        encoding: 'utf8',
        flag: 'wx',
      })
    }
    known.set(pkg.id, pkg)
  }
  const ids = [...known.keys()].sort()
  const paths = await Promise.all(
    ids.map(async (id) => {
      const hash = id + '--' + packageDigest(known.get(id)!).slice(0, 16)
      try {
        await stat(resolve(folder, hash + '.json'))
        return hash
      } catch (error) {
        if (!error || typeof error !== 'object' || !('code' in error) || error.code !== 'ENOENT')
          throw error
        await stat(resolve(folder, id + '.json'))
        return id
      }
    }),
  )
  const source =
    `// Generated by scripts/import-content.ts. Do not edit by hand.\nimport type { ContentPackage } from '../ingestion'\n` +
    paths.map((path, i) => `import p${i} from './packages/${path}.json'`).join('\n') +
    `\nexport const installedPackages: ContentPackage[] = [${ids.map((_, i) => 'p' + i + ' as ContentPackage').join(', ')}]\n`
  const temp = registry + '.' + crypto.randomUUID() + '.tmp'
  try {
    await writeFile(temp, await format(source, { ...config, parser: 'typescript' }), {
      encoding: 'utf8',
      flag: 'wx',
    })
    await beforeActivate?.()
    await rename(temp, registry)
  } finally {
    await rm(temp, { force: true })
  }
}
